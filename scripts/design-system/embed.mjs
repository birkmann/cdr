// Embeds packages/design-system/templates/** into packages/design-system/src/templates.generated.ts, so the component
// sources ship inside the compiled package and the esbuild bundles (no file lookup at runtime).
// Run after changing a template: node scripts/design-system/embed.mjs   (a test checks the hash is current).
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const dir = path.join(root, "packages/design-system/templates");
const files = {};
const walk = (d) => {
  for (const name of fs.readdirSync(d).sort()) {
    const p = path.join(d, name);
    if (fs.statSync(p).isDirectory()) walk(p);
    else files[path.relative(dir, p).split(path.sep).join("/")] = fs.readFileSync(p, "utf8");
  }
};
walk(dir);
const h = createHash("sha256");
for (const [k, v] of Object.entries(files)) h.update(k).update("\0").update(v).update("\0");
const out =
  "// Generated by scripts/design-system/embed.mjs from packages/design-system/templates. Do not edit.\n" +
  `export const TEMPLATES_HASH = ${JSON.stringify(h.digest("hex").slice(0, 16))};\n` +
  `export const TEMPLATES: Record<string, string> = ${JSON.stringify(files, null, 1)};\n`;
fs.writeFileSync(path.join(root, "packages/design-system/src/templates.generated.ts"), out);
console.log(`embedded ${Object.keys(files).length} design-system templates`);
