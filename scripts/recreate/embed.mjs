// Regenerates the embedded-source modules of the recreate packages, so text that must ship verbatim lives inside the
// compiled packages and the esbuild bundles (no file lookup at runtime):
//   packages/capture/src/generated.ts  ← assets/domCapture.js + assets/personalization.json (the in-page capture)
//   packages/codegen/src/export/generated.ts ← src/export/interactionsRuntime.ts (src/lib/interactions.ts of React exports)
// Run after changing any source: node scripts/recreate/embed.mjs   (tests check the hashes are current).
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const hash = (...parts) => {
  const h = createHash("sha256");
  for (const p of parts) h.update(p);
  return h.digest("hex").slice(0, 16);
};
const HEAD = (from) => `// Generated by scripts/recreate/embed.mjs from ${from}. Do not edit.\n`;

const script = read("packages/capture/assets/domCapture.js");
const blocked = JSON.parse(read("packages/capture/assets/personalization.json")).urls ?? [];
fs.writeFileSync(
  path.join(root, "packages/capture/src/generated.ts"),
  HEAD("assets/domCapture.js and assets/personalization.json") +
    `export const DOM_CAPTURE_HASH = ${JSON.stringify(hash(script, JSON.stringify(blocked)))};\n` +
    `export const DOM_CAPTURE_SOURCE: string = ${JSON.stringify(script)};\n` +
    `export const PERSONALIZATION_BLOCKLIST: readonly string[] = ${JSON.stringify(blocked)};\n`,
);

const runtime = read("packages/codegen/src/export/interactionsRuntime.ts");
fs.writeFileSync(
  path.join(root, "packages/codegen/src/export/generated.ts"),
  HEAD("src/export/interactionsRuntime.ts") +
    `export const INTERACTIONS_RUNTIME_HASH = ${JSON.stringify(hash(runtime))};\n` +
    `export const INTERACTIONS_RUNTIME_SOURCE: string = ${JSON.stringify(runtime)};\n`,
);
// axe-core (MPL-2.0, unmodified; THIRD_PARTY_NOTICES.md): the a11y gate runs it inside the measured page
const axePath = path.join(root, "packages/measure/node_modules/axe-core/axe.min.js");
if (fs.existsSync(axePath)) {
  const axe = fs.readFileSync(axePath, "utf8");
  const version = JSON.parse(fs.readFileSync(path.join(path.dirname(axePath), "package.json"), "utf8")).version;
  fs.writeFileSync(
    path.join(root, "packages/measure/src/axe.generated.ts"),
    HEAD(`axe-core ${version} (node_modules/axe-core/axe.min.js, MPL-2.0)`) +
      `export const AXE_VERSION = ${JSON.stringify(version)};\n` +
      `export const AXE_SOURCE: string = ${JSON.stringify(axe)};\n`,
  );
}
console.log("embedded capture script, interactions runtime and axe-core");
