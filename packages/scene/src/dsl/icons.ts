/** The icon's node list, or null when the name (or its alias) is unknown. */
export function iconNodesByName(name: string | undefined): IconNode | null {
  if (!name) return null;
  const key = name.trim().toLowerCase();
  const bare = key.replace(/^(lucide-|icon-|ic-)/, "").replace(/-(outline|filled|fill|solid|icon)$/, "");
  for (const c of [ALIASES[key], key, bare, ALIASES[bare]]) if (c && ICONS[c]) return ICONS[c];
  return null;
}

/** Icon nodes or the generic fallback (a circle). */
export function iconNodesOrFallback(name: string | undefined): IconNode {
  return iconNodesByName(name) ?? ICONS.circle;
}
