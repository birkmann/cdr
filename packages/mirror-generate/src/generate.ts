/** Rewrite url(...) references in ported CSS that point at the design root (design/assets/x → /_design/assets/x). */
export function rewriteCssUrls(css: string): string {
  return css.replace(/url\(\s*(['"]?)([^'")]+)\1\s*\)/g, (m, q: string, u: string) => {
    if (/^(data:|https?:|\/\/|#)/.test(u)) return m;
    if (u.startsWith("design/") || u.startsWith("/design/")) return `url(${q}/_design/${u.replace(/^\/?design\//, "")}${q})`;
    return m;
  });
}

function propsForRegistry(props: DesignProp[], example?: Record<string, unknown>) {
  const get = (path: string) => path.split(".").reduce<unknown>((o, k) => (o && typeof o === "object" ? (o as Record<string, unknown>)[k] : undefined), example);
  return props.map((p) => {
    const out: Record<string, unknown> = { ...p };
    if (!p.ccmField && !p.i18n && !p.component && p.type !== "list") {
      const ex = get(p.name);
      if (ex !== undefined && (typeof ex !== "object" || ex === null)) out.example = ex;
    }
    // menus: the mined items (state flags cleared) render when the CCM navigation is empty (lib/render/runtime.tsx)
    if (p.type === "list" && p.ccmField?.startsWith("navigation.")) {
      const ex = get(p.name);
      const clear = (items: unknown): unknown => (Array.isArray(items) ? items.map((it) => (it && typeof it === "object" ? { ...(it as object), active: false, activeTrail: false, children: clear((it as { children?: unknown }).children ?? []) } : it)) : items);
      if (Array.isArray(ex) && ex.length) out.example = clear(ex);
    }
    return out;
  });
}

function fieldTsType(f: CcmData["schema"]["contentTypes"][number]["fields"][number]): string {
  const many = (f.cardinality ?? 1) !== 1;
  let t: string;
  switch (f.type) {
    case "text":
    case "slug":
    case "enum":
    case "date":
      t = "string";
      break;
    case "number":
      t = "number";
      break;
    case "boolean":
      t = "boolean";
      break;
    case "richText":
      t = "RichTextDoc";
      break;
    case "link":
      t = "LinkView";
      break;
    case "component":
      t = "EntryView";
      break;
    case "componentList":
      return "EntryView[]";
    case "reference": {
      const a = f.allowedTypes ?? [];
      t = a.includes("asset") ? "AssetView | null" : a.some((x) => x.startsWith("term:")) ? "TermView | null" : "EntryView | EntryStub";
      if (many) return `(${t.replace(" | null", "")})[]`;
      break;
    }
    default:
      t = "unknown";
  }
  return many ? `${t.includes("|") ? `(${t})` : t}[]` : t;
}

export function typesTs(schema: CcmData["schema"]): string {
  const L = [
    `// ${GEN_HEADER}`,
    "// Field types of the resolved entries returned by the data layer (src/lib/data), from ccm/schema/content-types.json.",
    'import type { RichTextDoc } from "../lib/ccm-types";',
    'import type { AssetView, EntryStub, EntryView, LinkView, TermView } from "../lib/data/types";',
    "",
  ];
  const ids: string[] = [];
  for (const t of [...schema.contentTypes].sort((a, b) => a.id.localeCompare(b.id))) {
    ids.push(t.id);
    L.push(`/** ${t.name} (${t.kind ?? "document"}) */`, `export interface ${pascalCase(t.id)}Fields {`);
    for (const f of t.fields) L.push(`  ${/^[a-zA-Z_$][\w$]*$/.test(f.id) ? f.id : JSON.stringify(f.id)}${f.required ? "" : "?"}: ${fieldTsType(f)};`);
    L.push("}", "");
  }
  L.push(`export type ContentTypeId = ${ids.length ? ids.map((i) => JSON.stringify(i)).join(" | ") : "string"};`, "");
  L.push("export interface FieldsByType {", ...ids.map((i) => `  ${JSON.stringify(i)}: ${pascalCase(i)}Fields;`), "}", "");
  return L.join("\n");
}

