async function readCcm(root: string): Promise<CcmData> {
  const list = async (sub: string) => {
    const files = (await walk(join(root, sub))).filter((f) => f.endsWith(".json"));
    return Promise.all(files.map((f) => readJsonOr<unknown>(join(root, sub, f), null))).then((xs) => xs.filter(Boolean));
  };
  return {
    schema: await readJsonOr(join(root, "schema/content-types.json"), { contentTypes: [] }),
    locales: await readJsonOr(join(root, "i18n/locales.json"), []),
    redirects: await readJsonOr(join(root, "redirects/redirects.json"), []),
    entries: (await list("entries")) as CcmData["entries"],
    assets: (await list("assets")) as CcmData["assets"],
    collections: (await list("collections")) as CcmData["collections"],
    settings: await readJsonOr(join(root, "settings/site.json"), null),
  };
}

