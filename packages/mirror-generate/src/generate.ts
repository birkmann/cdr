const prefixOf = (l: { default?: boolean; pathPrefix?: string; code: string }) => {
  if (l.default) return "";
  const p = (l.pathPrefix ?? l.code).replace(/^\/+|\/+$/g, "");
  return p ? "/" + p : "";
};
/** path-to-regexp special characters in a literal source path */
const escapeSource = (p: string) => p.replace(/[()[\]{}?+*:!]/g, (c) => "\\" + c);
/** an absolute URL, or a path (with optional query/hash) free of path-to-regexp syntax */
const isLiteralDestination = (to: string) => {
  if (/^https?:\/\//i.test(to)) {
    try {
      const u = new URL(to);
      return !/[()[\]{}*+!]|:(?=[A-Za-z_])/.test(u.pathname);
    } catch {
      return false;
    }
  }
  return to.startsWith("/") && !/[()[\]{}*+!:\s]/.test(to.split(/[?#]/)[0]!);
};

export function buildRedirects(ccm: CcmData, issues: Issue[]) {
  const out = new Map<string, { from: string; to: string; status: number; locale?: string }>();
  for (const r of ccm.redirects) out.set(r.from, { from: r.from, to: r.to, status: r.status ?? 301, locale: r.locale });
  // /node/<nid> (and /<prefix>/node/<nid>) → alias, if the CCM did not list them already (§14 #5)
  for (const e of ccm.entries) {
    if (e.source?.system !== "drupal" || e.source.kind !== "node" || !e.path || (e.status && e.status !== "published")) continue;
    const l = ccm.locales.find((x) => x.code === e.locale) ?? { code: e.locale, default: true };
    const from = `${prefixOf(l)}/node/${e.source.id}`;
    if (!out.has(from)) out.set(from, { from, to: e.path, status: 301, locale: e.locale });
  }
  const pages = new Set(ccm.entries.map((e) => e.path).filter(Boolean));
  const list = [...out.values()]
    .filter((r) => {
      if (r.from === r.to) return false;
      // Next parses the destination with path-to-regexp: a literal `*`, `(`, `:` … (a server's broken geo template such as
      // ibm.com's `Location: /de-*`) fails the whole build with "Invalid redirect found"
      if (!isLiteralDestination(r.to)) {
        issues.push({ severity: "warning", code: "REDIRECT_INVALID_DESTINATION", message: `redirect ${r.from} → ${r.to} skipped: the destination is not a usable path`, ref: r.from, actionable: true });
        return false;
      }
      if (pages.has(r.from)) {
        issues.push({ severity: "warning", code: "REDIRECT_SHADOWS_PAGE", message: `redirect ${r.from} → ${r.to} skipped: ${r.from} is a live page`, ref: r.from });
        return false;
      }
      return true;
    })
    .sort((a, b) => a.from.localeCompare(b.from));
  return {
    ccm: list,
    next: list.map((r) => ({ source: escapeSource(r.from), destination: r.to, statusCode: r.status })),
  };
}

