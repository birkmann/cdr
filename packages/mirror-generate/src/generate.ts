async function readJsonOr<T>(p: string, fallback: T): Promise<T> {
  try {
    return JSON.parse(await readFile(p, "utf8")) as T;
  } catch {
    return fallback;
  }
}
async function walk(dir: string, base = dir): Promise<string[]> {
  const out: string[] = [];
  let ents;
  try {
    ents = await readdir(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of ents) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p, base)));
    else out.push(relative(base, p).split(sep).join("/"));
  }
  return out.sort();
}
function findRepoRoot(start: string): string {
  let dir = resolve(start);
  for (;;) {
    if (existsSync(join(dir, "pnpm-workspace.yaml"))) return dir;
    const up = dirname(dir);
    if (up === dir) return resolve(start);
    dir = up;
  }
}
/**
 * Text files ported from a replayed capture carry the replay's absolute URLs (`http://localhost:4401/x`,
 * `…/__ext/<host>/x` for captured third parties). In the generated app they become root-relative so it never
 * depends on the replay: same-origin → `/x`, third party → `/__ext/<host>/x` (served from public/, crawled copy).
 */
export function unReplayText(text: string, replay: string | undefined): string {
  if (!replay) return text;
  const host = replay.replace(/^https?:/, "").replace(/\/+$/, "");
  const esc = host.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const jhost = host.replace(/\//g, "\\/");
  const bare = esc.replace(/^\\\/\\\//, "").replace(/^\/\//, "");
  return text
    // scheme-less host strings the JS prefixes itself (`proto + "//" + "host/…"`): back to the third-party host
    .replace(new RegExp(`(?<![/\\w.-])${bare}/__ext/`, "g"), "")
    .replace(new RegExp(`(?:https?:)?${esc}(?=[/"'?#\\s)]|$)`, "g"), "")
    .split(`http:${jhost}`).join("")
    .split(`https:${jhost}`).join("");
}
