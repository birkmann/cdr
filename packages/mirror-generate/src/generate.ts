const SKIP_FETCH = Symbol("skip");

const isLoopback = (u: string) => {
  try {
    return /^(localhost|127\.\d+\.\d+\.\d+|\[::1\])$/.test(new URL(u).hostname);
  } catch {
    return false;
  }
};

/**
 * URL to download a public path / asset src from. Paths resolve against the source baseUrl. Absolute URLs of the old
 * origin are re-hosted onto the source baseUrl. When the source is local (a replay of captured pages, a fixture
 * server) nothing is ever fetched from a non-local host — captured sites may forbid automated access.
 */
export function fetchUrlFor(srcOrPath: string, sourceBase: string, oldOrigins: string[]): string | undefined {
  const base = sourceBase.replace(/\/+$/, "");
  if (srcOrPath.startsWith("/") && !srcOrPath.startsWith("//")) return base + srcOrPath;
  const abs = srcOrPath.startsWith("//") ? "https:" + srcOrPath : srcOrPath;
  let u: URL;
  try {
    u = new URL(abs);
  } catch {
    return undefined;
  }
  const old = oldOrigins.some((o) => {
    try {
      return new URL(o).host === u.host;
    } catch {
      return false;
    }
  });
  if (old) return base + u.pathname + u.search;
  if (isLoopback(base) && !isLoopback(abs)) return undefined;
  return abs;
}

async function fetchBinary(url: string, f: typeof fetch): Promise<Uint8Array | typeof SKIP_FETCH> {
  try {
    const res = await f(url, { signal: AbortSignal.timeout(10_000) });
    if (!res.ok) return SKIP_FETCH;
    return new Uint8Array(await res.arrayBuffer());
  } catch {
    return SKIP_FETCH;
  }
}

export async function planGeneration(ctx: StepContext, appAbs: string, opts: GenerateOptions): Promise<Planned> {
  const { ws, site } = ctx;
  const issues: Issue[] = [];
  const generated = new Map<string, string | Uint8Array>();
  const publicFiles = new Map<string, string | Uint8Array>();
  const stats: Record<string, number | string | boolean> = {};
  const doFetch = opts.download === false ? undefined : (opts.fetch ?? globalThis.fetch);
  const ccmRoot = ws.path("ccm");
  const ccm = await readCcm(ccmRoot);
  // downloads go to the configured source (sites/<site>.yaml baseUrl — for captured sites the local replay), never to
  // the old live origin from the CCM settings: see fetchUrlFor()
  const baseUrl = site.baseUrl.replace(/\/+$/, "");
  const oldOrigins = [ccm.settings?.baseUrl].filter((x): x is string => !!x);
  const dataSource = site.frontend.dataSource;

  // -------- config
  const dateLocales: Record<string, string> = {};
  for (const l of ccm.locales) dateLocales[l.code] = l.code === "en" ? "en-GB" : l.code.includes("-") ? l.code : `${l.code}-${l.code.toUpperCase()}`;
  generated.set(
    "config.json",
    json({
      site: site.site,
      dataSource,
      ccmDir: relative(appAbs, ccmRoot).split(sep).join("/") || ".",
      siteUrl: "",
      contentful: { spaceIdEnv: site.target.contentful.spaceIdEnv, environment: site.target.contentful.environment ?? "master" },
      dateLocales,
      // /api/files upstream policy: old-origin URLs are re-hosted onto the source; a local source never leads to
      // requests to other hosts (captured sites)
      assetSource: { base: site.baseUrl.replace(/\/+$/, ""), oldOrigins: [ccm.settings?.baseUrl].filter(Boolean), localOnly: isLoopback(site.baseUrl) },
    }),
  );
  generated.set("schema.json", json(ccm.schema));
  generated.set("locales.json", json(ccm.locales.map((l) => ({ code: l.code, name: l.name, default: !!l.default, fallback: l.fallback, pathPrefix: l.pathPrefix ?? "" }))));
  generated.set("types.ts", typesTs(ccm.schema));

  // -------- routing
  const r = buildRedirects(ccm, issues);
  // the site root: the original answers / with its start page (bvg.de -> /de, ibm.com -> /us-en). Without a page or a
  // recorded redirect for /, send it to the first configured page instead of a 404.
  const start = (site.urls ?? [])[0];
  if (start && start !== "/" && !ccm.entries.some((e) => e.path === "/") && !r.next.some((x) => x.source === "/")) {
    r.next.push({ source: "/", destination: start, statusCode: 307 });
    issues.push({ severity: "info", code: "ROOT_REDIRECT_ADDED", message: `/ has no page: redirected to the start page ${start}`, ref: "/" });
  }
  generated.set("redirects-ccm.json", json(r.ccm));
  generated.set("routing.json", json({ redirects: r.next, rewrites: [{ source: "/sites/default/files/:path*", destination: "/api/files/:path*" }] }));
  stats.redirects = r.next.length;

  // -------- assets: Contentful id map (asset-map.json from the loader, else idmap.json) + binaries (ccm mode)
  const assetMap = await readJsonOr<Record<string, { assetId?: string; ccmId?: string; url?: string }>>(ws.path("target/contentful/asset-map.json"), {});
  const idmap = await readJsonOr<Record<string, Record<string, string>>>(ws.path("idmap.json"), {});
  const cf: Record<string, { ccmId?: string; originalPath?: string; width?: number; height?: number }> = {};
  for (const a of ccm.assets) {
    const fromMap = a.originalPath ? assetMap[a.originalPath]?.assetId : undefined;
    const fromIdmap = Object.entries(idmap).find(([t]) => t.includes("contentful"))?.[1]?.[a.ccmId];
    const id = fromMap ?? fromIdmap;
    if (id) cf[id] = { ccmId: a.ccmId, originalPath: a.originalPath, width: a.width, height: a.height };
  }
  generated.set("assets.json", json({ contentful: Object.fromEntries(Object.entries(cf).sort(([a], [b]) => a.localeCompare(b))) }));

  const localBinary = async (publicPath: string, src?: string): Promise<Uint8Array | undefined> => {
    const rel = publicPath.split("?")[0].replace(/^\/+/, "");
    for (const cand of [src && !/^(https?:)?\/\//.test(src) ? ws.path(src) : undefined, ws.path("raw/html/assets", rel), ws.path("raw/html/assets", safeDecode(rel)), ws.path("raw/files", rel), ws.path("raw/files", rel.replace(/^sites\/default\/files\//, ""))]) {
      if (cand && (await exists(cand)) && (await stat(cand)).isFile()) return new Uint8Array(await readFile(cand));
    }
    if (!doFetch) return undefined;
    const url = fetchUrlFor(src && /^(https?:)?\/\//.test(src) ? src : publicPath, baseUrl, oldOrigins);
    if (!url) return undefined;
    const got = await fetchBinary(url, doFetch);
    return got === SKIP_FETCH ? undefined : got;
  };

  if (dataSource === "ccm") {
    let copied = 0;
    for (const a of ccm.assets) {
      const pub = a.originalPath ?? `/_assets/${safeId(a.ccmId)}/${a.fileName}`; // same safeId as the app (lib/data/store.ts)
      const bin = await localBinary(pub, a.src);
      if (bin) {
        publicFiles.set(safeDecode(pub.split("?")[0]).replace(/^\/+/, ""), bin);
        copied++;
      } else issues.push({ severity: "warning", code: "ASSET_BINARY_MISSING", message: `no local binary for ${a.ccmId} (${pub}); served via /api/files proxy from ${a.src}`, ref: a.ccmId });
    }
    stats.assetsCopied = copied;
  }

  // -------- design
  const design = await readDesign(ws.path("design"), issues);
  const designJson: DesignJsonOut = {
    stylesheets: [],
    scripts: [],
    htmlAttrs: {},
  };
  const localScripts = new Map<string, string | undefined>(); // public path → design-relative source (if any)
  if (design) {
    await planDesign(design, generated, publicFiles, designJson, localScripts, issues, stats, ccm.collections);
  } else {
    issues.push({ severity: "warning", code: "DESIGN_MISSING", message: "design/ not found — pages render with the plain fallback components (run `migrate design extract` first)", actionable: true });
    generated.set("registry.ts", emptyRegistry());
  }
  if (designJson.renderMode === "static") {
    await applyCrawledHeads(ws.path("raw/html"), ccm, designJson, localScripts, issues, stats);
    // captured sources: replay URLs → root-relative / third-party host, old-origin resource URLs → root-relative
    designJson.urlRewrite = { ...(isLoopback(site.baseUrl) ? { replay: baseUrl } : {}), ...(ccm.settings?.baseUrl && ccm.settings.baseUrl.replace(/\/+$/, "") !== baseUrl ? { origin: ccm.settings.baseUrl.replace(/\/+$/, "") } : {}) };
  }
  if (designJson.renderMode === "static") {
    await collectSiteFiles(ws, ccm, design, baseUrl, publicFiles, localBinary, issues, stats);
    // live source: its markup references images/scripts by absolute URL on its own origin; the crawled copies are served
    // from public/ (a CDN may refuse a page on another origin, e.g. ibm.com images blocked as cross-origin from localhost)
    if (!isLoopback(site.baseUrl)) {
      const paths = [...publicFiles.keys()].filter((k) => !k.startsWith("_design/")).map((k) => "/" + k).sort();
      designJson.urlRewrite = { ...((designJson.urlRewrite as object | undefined) ?? {}), local: { origin: baseUrl, paths } };
      // safety net: code the crawl did not see (a chunk loaded only by an interaction it did not exercise) is fetched from
      // the source instead of failing the page's scripts; files in public/ always win (Next afterFiles rewrites)
      const crawledCode = await readJsonOr<{ path: string; kind?: string }[]>(ws.path("raw/html/assets.json"), []);
      const dirs = [...new Set(crawledCode.filter((a) => (a.kind === "script" || a.kind === "stylesheet") && /^\/[^/]+\/./.test(a.path)).map((a) => "/" + a.path.split("/")[1]))].filter((d) => !APP_OWNED_PATH.test(d)).sort();
      if (dirs.length) {
        const routing = JSON.parse(generated.get("routing.json") as string) as Record<string, unknown>;
        routing.assetProxies = dirs.map((d) => ({ source: `${d}/:path*`, destination: `${baseUrl}${d}/:path*` }));
        generated.set("routing.json", json(routing));
      }
    }
    // third-party resources the crawl captured are served from public/__ext/<host>/. The content keeps their original
    // absolute URLs (CCM stays portable); the app points resource references at the local copy, so the page does not
    // depend on a CDN that may refuse other origins or be unreachable (verify blocks it next to a replay). Scripts stay
    // external, as before: their copies are kept for the replay, not as a substitute for the vendor's current code.
    const thirdParty = [...publicFiles.keys()].filter((k) => k.startsWith("__ext/") && !/\.m?js$/i.test(k)).map((k) => "/" + k).sort();
    if (thirdParty.length) designJson.urlRewrite = { ...((designJson.urlRewrite as object | undefined) ?? {}), thirdParty: { paths: thirdParty } };
  }
  else {
    await collectCrawledFiles(ws, baseUrl, publicFiles, stats);
    designJson.pageAttrs = await crawledPageAttrs(ws.path("raw/html"), dirname(ws.path("raw")));
    // menus / mobile nav: the source's scripts do not run here, the app replays what its toggles changed (NavInteractions)
    designJson.interactions = await crawledInteractions(ws.path("raw/html"));
  }
  // site scripts (cookie consent / analytics) from SiteSettings must be served from the same path as on the old site
  for (const s of ccm.settings?.scripts ?? []) if (s.src && s.src.startsWith("/") && !s.src.startsWith("//") && !(designJson.renderMode === "static" && isTrackerText(s.src))) localScripts.set(s.src.split("?")[0], localScripts.get(s.src.split("?")[0]));
  for (const [pub, designRel] of [...localScripts].sort()) {
    if (pub.startsWith("/_design/")) continue; // copied with the design folder
    let bin = designRel && design ? new Uint8Array(await readFile(join(design.dir, designRel))) : await localBinary(pub);
    if (bin && designJson.renderMode === "static" && TEXT_FILE.test(pub)) bin = new TextEncoder().encode(unReplayText(new TextDecoder().decode(bin), isLoopback(site.baseUrl) ? baseUrl : undefined));
    // public/ is looked up with the decoded request path (/%40scope/x.js → public/@scope/x.js)
    if (bin) publicFiles.set(safeDecode(pub).replace(/^\/+/, ""), bin);
    else issues.push({ severity: "warning", code: "SCRIPT_MISSING", message: `site script ${pub} not found in design/, raw/html/assets or on ${baseUrl}`, ref: pub });
  }
  siteOverridesLast(designJson);
  generated.set("design.json", json(designJson));

  // -------- SEO tag rules (og:*, twitter:*) learned from the crawled original pages
  const inferred = await planSeo(ws.path("raw/html"), ccm);
  // explicit, reviewed rules (mapping/seo.yaml, e.g. from the autofix seo-rule handler) win over inferred ones per tag
  let explicitSeo: unknown;
  if (existsSync(ws.path("mapping/seo.yaml")))
    try {
      explicitSeo = YAML.parse(await readFile(ws.path("mapping/seo.yaml"), "utf8"));
    } catch (e) {
      issues.push({ severity: "error", code: "SEO_RULES_INVALID", message: `mapping/seo.yaml: ${(e as Error).message.split("\n")[0]}`, ref: "mapping/seo.yaml", actionable: true });
    }
  const seo = mergeSeoRules(inferred, explicitSeo);
  if (seo.applied.length) stats.seoRulesExplicit = seo.applied.length;
  if (seo.invalid.length) issues.push({ severity: "warning", code: "SEO_RULES_INVALID", message: `mapping/seo.yaml: invalid rule(s) skipped: ${seo.invalid.join(", ")}`, ref: "mapping/seo.yaml" });
  generated.set("seo.json", json({ rules: seo.rules, order: seo.order }));
  stats.seoRules = seo.order.length;
  if (seo.rejected.length) issues.push({ severity: "info", code: "SEO_RULE_UNRESOLVED", message: `head tags without a consistent rule (not reproduced unless in CCM meta): ${seo.rejected.join(", ")}` });
  // public files without a file extension (scene7 renditions `…/x:3to1`, bmw.de `…/skins/BMW/AI-label`) get
  // application/octet-stream from Next; browsers sniff raster images but never SVG, so such an icon stays blank. The
  // crawl recorded the original Content-Type: routing.json carries it and next.config.ts sends it for those paths.
  const contentTypes = await contentTypeHeaders(ws, publicFiles);
  if (contentTypes.length) {
    generated.set("routing.json", json({ ...(JSON.parse(generated.get("routing.json") as string) as object), headers: contentTypes }));
    stats.contentTypeHeaders = contentTypes.length;
  }
  stats.dataSource = dataSource;
  return { generated, publicFiles, issues, stats };
}

/** a literal path as a Next route `source`: path-to-regexp specials escaped */
export const routeSource = (path: string): string => path.replace(/[(){}:*+?]/g, "\\$&");

/** Content-Type header rules for extension-less public files whose MIME type the crawl recorded (raw/html/assets.json). */
export async function contentTypeHeaders(ws: StepContext["ws"], publicFiles: Map<string, unknown>): Promise<{ source: string; headers: { key: string; value: string }[] }[]> {
  const assets = await readJsonOr<{ path?: string; mime?: string }[]>(ws.path("raw/html/assets.json"), []);
  const mimeByRel = new Map<string, string>();
  for (const a of assets) {
    const mime = a.mime?.split(";")[0]!.trim();
    if (mime && a.path?.startsWith("/")) mimeByRel.set(safeDecode(a.path.split("?")[0]!).replace(/^\/+/, ""), mime);
  }
  const out: { source: string; headers: { key: string; value: string }[] }[] = [];
  for (const rel of [...publicFiles.keys()].sort()) {
    if (/\.[A-Za-z0-9]{1,8}$/.test(rel.split("/").pop()!)) continue; // Next infers the type from the extension
    const mime = mimeByRel.get(rel);
    if (!mime || mime === "application/octet-stream") continue;
    out.push({ source: routeSource("/" + rel), headers: [{ key: "Content-Type", value: mime }] });
  }
  return out;
}

/**
 * design/overrides/site.css (published by @cmp/design as styles/site-overrides.css) must win the cascade: move it to
 * the end of every stylesheet list of design.json (global, per type, per page), whatever was added after the merge.
 */
export function siteOverridesLast(designJson: Record<string, unknown>): void {
  const isSite = (x: unknown) => {
    const h = typeof x === "string" ? x : x && typeof x === "object" ? (x as { href?: unknown }).href : undefined;
    return typeof h === "string" && /(^|\/)styles\/site-overrides\.css(\?|$)/.test(h);
  };
  const fix = (v: unknown) => {
    const list = v && typeof v === "object" ? (v as { stylesheets?: unknown[] }).stylesheets : undefined;
    if (!Array.isArray(list) || !list.some(isSite)) return;
    (v as { stylesheets: unknown[] }).stylesheets = [...list.filter((x) => !isSite(x)), ...list.filter(isSite)];
  };
  fix(designJson);
  for (const k of ["types", "pages"]) for (const v of Object.values((designJson[k] as Record<string, unknown> | undefined) ?? {})) fix(v);
}

/**
 * Static mode: the <head> item list and <html>/<body> attributes of each crawled original page (raw server HTML)
 * become the page variant (exact path) and, for its content type, the default (example page). Local files the
 * literal head markup references (favicons, mask icon, …) are served at their original paths.
 */
async function applyCrawledHeads(rawHtml: string, ccm: CcmData, designJson: DesignJsonOut, localScripts: Map<string, string | undefined>, issues: Issue[], stats: Record<string, number | string | boolean>) {
  const index = await readJsonOr<{ pages?: { path: string; id: string; status: number; files?: { raw?: string } }[] }>(join(rawHtml, "crawl.json"), {});
  const pages = (designJson.pages ??= {}) as Record<string, Record<string, unknown>>;
  const types = (designJson.types ??= {}) as Record<string, Record<string, unknown>>;
  const removed = new Set<string>();
  let n = 0;
  // crawled Views listing pages (Collection.path / crawl-derived collections): no CCM entry, but a crawled head
  const listingPaths = new Set<string>();
  for (const c of ccm.collections) {
    if (typeof c.path === "string") listingPaths.add(c.path);
    else if (c.path) for (const p of Object.values(c.path)) listingPaths.add(p);
    if (!c.path && c.source?.system === "html" && c.source.url?.startsWith("/")) listingPaths.add(c.source.url);
  }
  for (const pg of index.pages ?? []) {
    if (pg.status !== 200) continue;
    const e = ccm.entries.find((x) => x.path === pg.path);
    const listing = !e && listingPaths.has(pg.path);
    if (!e && !listing) continue;
    const wsRoot = dirname(dirname(rawHtml));
    const file = [pg.files?.raw ? join(wsRoot, pg.files.raw) : "", join(rawHtml, "pages", `${pg.id}.raw.html`)].find((f) => f && existsSync(f));
    if (!file) continue;
    const h = headFromHtml(await readFile(file, "utf8"));
    h.removed.forEach((r) => removed.add(r));
    pages[pg.path] = { ...(pages[pg.path] ?? {}), head: h.head, htmlAttrs: h.htmlAttrs, bodyAttrs: h.bodyAttrs, ...(listing && h.title ? { title: h.title } : {}) };
    const t = (types[e?.type ?? "collection"] ??= {});
    if (!t.head) {
      t.head = h.head;
      t.htmlAttrs = h.htmlAttrs;
    }
    if (!designJson.head) designJson.head = h.head;
    for (const it of h.head)
      if (it.html) for (const m of it.html.matchAll(/\s(?:href|src)="(\/[^/"][^"]*)"/g)) {
        const pub = m[1].split("?")[0].split("#")[0];
        if (!localScripts.has(pub)) localScripts.set(pub, undefined);
      }
    n++;
  }
  // stylesheets the original only loads inside <noscript> (e.g. seckit.noscript_tag.css un-hides <body>) must not
  // be applied as regular stylesheets
  const noscriptCss = new Set<string>();
  for (const pg of Object.values(pages))
    for (const it of (pg.head as { html?: string }[] | undefined) ?? [])
      if (it.html?.startsWith("<noscript")) for (const m of it.html.matchAll(/href="([^"]+\.css)[^"]*"/g)) noscriptCss.add(m[1].split("/").pop()!);
  if (noscriptCss.size) {
    const base = (h: string) => h.split("?")[0].split("/").pop()!;
    const prune = (v: Record<string, unknown> | undefined) => {
      const list = v?.stylesheets as { href?: string }[] | undefined;
      if (!list) return;
      const kept = list.filter((x) => !(x.href && noscriptCss.has(base(x.href))));
      if (kept.length !== list.length) {
        v!.stylesheets = kept;
        issues.push({ severity: "warning", code: "STYLESHEET_NOSCRIPT_ONLY", message: `${[...noscriptCss].join(", ")}: loaded inside <noscript> on the original — not applied as a regular stylesheet` });
      }
    };
    prune(designJson);
    for (const v of Object.values(types)) prune(v);
    for (const v of Object.values(pages)) prune(v);
  }
  stats.crawledHeads = n;
  if (removed.size) issues.push({ severity: "info", code: "TRACKERS_REMOVED", message: `head: not reproduced: ${[...removed].join(", ")}` });
}

const SITE_FILE = /(?:https?:(?:\\?\/){2}[a-zA-Z0-9.:-]+)?((?:\\?\/)(?:sites\/[^/"'\\]+\/files|themes|modules|libraries|core|profiles)(?:\\?\/)[^"'\s,)?\\<>]+(?:\\?\/[^"'\s,)?\\<>]+)*)/g;

/**
 * React mode: the <html>/<body> attributes of each crawled page as the visitor's browser ended up with them (rendered
 * DOM). Site CSS keys layout on them (`html[data-template=home] .Page_page{margin-top:0}`, body CSS variables a script
 * measured); the source's own JS does not run in the generated app, so the final state is taken over. `lang`/`dir`
 * come from the app's locale.
 */
async function crawledPageAttrs(rawHtml: string, wsRoot: string): Promise<Record<string, { html: Record<string, string>; body: Record<string, string> }>> {
  const index = await readJsonOr<{ pages?: { path: string; id: string; status: number; files?: { rendered?: string; raw?: string } }[] }>(join(rawHtml, "crawl.json"), {});
  const out: Record<string, { html: Record<string, string>; body: Record<string, string> }> = {};
  for (const pg of index.pages ?? []) {
    if (pg.status !== 200) continue;
    const file = [pg.files?.rendered ? join(wsRoot, pg.files.rendered) : "", join(rawHtml, "pages", `${pg.id}.rendered.html`)].find((f) => f && existsSync(f));
    if (!file) continue;
    const html = await readFile(file, "utf8");
    const tag = (name: string) => new RegExp(`<${name}\\b[^>]*>`, "i").exec(html)?.[0];
    const h = tag("html"), b = tag("body");
    const { lang: _l, dir: _d, ...htmlAttrs } = h ? startTagAttrs(h) : {};
    out[pg.path] = { html: htmlAttrs, body: b ? startTagAttrs(b) : {} };
  }
  return out;
}

/** header/nav toggle records per crawled page and viewport (source-html interactions.ts) */
async function crawledInteractions(rawHtml: string): Promise<Record<string, Record<string, { width: number; records: unknown[] }>>> {
  const index = await readJsonOr<{ pages?: { path: string; status: number; manifest?: string }[] }>(join(rawHtml, "crawl.json"), {});
  const out: Record<string, Record<string, { width: number; records: unknown[] }>> = {};
  for (const pg of index.pages ?? []) {
    if (pg.status !== 200 || !pg.manifest) continue;
    const m = await readJsonOr<{ interactions?: Record<string, { width: number; records: unknown[] }> }>(join(dirname(dirname(rawHtml)), pg.manifest), {});
    if (m.interactions && Object.keys(m.interactions).length) out[pg.path] = m.interactions;
  }
  return out;
}

/** Root-relative paths the generated app owns; a crawled file there would shadow or collide with the app (a Next.js source's own `/_next/` chunks). */
const APP_OWNED_PATH = /^\/(_next|api|_design|_assets)(\/|$)/;

/**
 * React mode: images and scripts the crawl browser loaded (raw/html/assets) are served at their original paths.
 * Design component markup, layouts and raw-HTML fallbacks keep the original root-relative `src`/`srcset`/`url()`
 * references (header logos, footer icons, srcset breakpoints), which are not CCM assets; the site scripts (served at
 * their original paths, see planDesign) load lazy chunks relative to themselves. Stylesheets are not copied: the design
 * step ports them with rewritten url()s.
 */
async function collectCrawledFiles(ws: StepContext["ws"], sourceBase: string, publicFiles: Map<string, string | Uint8Array>, stats: Record<string, number | string | boolean>) {
  const assets = await readJsonOr<{ path: string; url?: string; file?: string; kind?: string }[]>(ws.path("raw/html/assets.json"), []);
  // captured sources: scripts fetched through the local replay must not keep its loopback URL
  const replay = isLoopback(sourceBase) ? sourceBase : undefined;
  let copied = 0;
  for (const a of assets) {
    if ((a.kind !== "image" && a.kind !== "script") || !a.path?.startsWith("/") || a.path.startsWith("//") || isTrackerText(a.path) || isTrackerText(a.url)) continue;
    const rel = safeDecode(a.path.split("?")[0]!).replace(/^\/+/, "");
    if (!rel || APP_OWNED_PATH.test("/" + rel) || publicFiles.has(rel)) continue;
    const f = a.file ? ws.path(a.file) : ws.path("raw/html/assets", rel);
    if (!existsSync(f) || !(await stat(f)).isFile()) continue;
    const buf = new Uint8Array(await readFile(f));
    publicFiles.set(rel, replay && TEXT_FILE.test(rel) ? new TextEncoder().encode(unReplayText(new TextDecoder().decode(buf), replay)) : buf);
    copied++;
  }
  stats.crawledFilesCopied = copied;
}

/**
 * Static mode: every same-origin file the original pages load or reference is served at its original path —
 * files the crawl browser loaded (raw/html/assets: JS-requested icons, srcset candidates, fonts, …) and files
 * referenced by CCM / design markup (srcset breakpoints, data-* images), the latter downloaded from the source
 * (for captured sites: the local replay).
 */
async function collectSiteFiles(
  ws: StepContext["ws"],
  ccm: CcmData,
  design: Design | undefined,
  sourceBase: string,
  publicFiles: Map<string, string | Uint8Array>,
  localBinary: (publicPath: string) => Promise<Uint8Array | undefined>,
  issues: Issue[],
  stats: Record<string, number | string | boolean>,
) {
  const have = (pub: string) => publicFiles.has(safeDecode(pub).replace(/^\/+/, ""));
  let crawled = 0;
  const assets = await readJsonOr<{ path: string; url?: string; file?: string; kind?: string }[]>(ws.path("raw/html/assets.json"), []);
  for (const a of assets) {
    if (!a.path?.startsWith("/") || isTrackerText(a.path) || isTrackerText(a.url) || have(a.path)) continue;
    // the page itself, crawled as an asset (toyota.com `<img src="">`): written as a file it would take the place of public/
    if (!a.path.split("?")[0]!.replace(/^\/+/, "")) continue;
    const f = a.file ? ws.path(a.file) : ws.path("raw/html/assets", a.path.replace(/^\/+/, ""));
    if (!existsSync(f)) continue;
    const buf = new Uint8Array(await readFile(f));
    const replay = /^https?:\/\/(localhost|127\.0\.0\.1)/.test(sourceBase) ? sourceBase : undefined;
    publicFiles.set(safeDecode(a.path.split("?")[0]).replace(/^\/+/, ""), TEXT_FILE.test(a.path.split("?")[0]) && replay ? new TextEncoder().encode(unReplayText(new TextDecoder().decode(buf), replay)) : buf);
    crawled++;
  }
  const refs = new Set<string>();
  const scan = (text: string) => {
    for (const m of text.matchAll(SITE_FILE)) {
      const p = m[1].replace(/\\\//g, "/").replace(/&amp;/g, "&");
      if (/\.(png|jpe?g|gif|svg|webp|avif|ico|woff2?|ttf|otf|eot|mp4|webm|pdf|json|js|css)$/i.test(p)) refs.add(p);
    }
  };
  for (const e of ccm.entries) scan(JSON.stringify(e.fields ?? {}));
  scan(JSON.stringify(ccm.settings ?? {}));
  for (const c of design?.components ?? []) scan(c.template + JSON.stringify((c as unknown as { instanceProps?: unknown }).instanceProps ?? {}));
  if (design?.layout) scan(JSON.stringify(design.layout));
  for (const t of design?.templates ?? []) scan(t.wrapperHtml ?? "");
  const todo = [...refs].filter((p) => !have(p) && !isTrackerText(p)).sort();
  let fetched = 0;
  const missing: string[] = [];
  for (let i = 0; i < todo.length; i += 4) {
    await Promise.all(
      todo.slice(i, i + 4).map(async (p) => {
        const bin = await localBinary(p);
        if (bin) {
          publicFiles.set(safeDecode(p).replace(/^\/+/, ""), bin);
          fetched++;
        } else missing.push(p);
      }),
    );
  }
  stats.siteFilesCrawled = crawled;
  stats.siteFilesFetched = fetched;
  if (missing.length) issues.push({ severity: "warning", code: "SITE_FILE_MISSING", message: `${missing.length} referenced site files not available from raw/html/assets or ${sourceBase}: ${missing.slice(0, 20).join(", ")}${missing.length > 20 ? " …" : ""}` });
}

/** first asset reference of an entry (own fields first, then referenced component entries) → public path */
function primaryImage(ccm: CcmData, e: CcmData["entries"][number]): string | undefined {
  const assets = new Map(ccm.assets.map((a) => [a.ccmId, a]));
  const isRef = (v: unknown, kind: string): v is { kind: string; id: string } => !!v && typeof v === "object" && (v as { kind?: string }).kind === kind && typeof (v as { id?: string }).id === "string";
  const flat = (v: unknown) => (Array.isArray(v) ? v : [v]);
  for (const v of Object.values(e.fields ?? {})) for (const x of flat(v)) if (isRef(x, "asset")) return assets.get(x.id)?.originalPath;
  for (const v of Object.values(e.fields ?? {}))
    for (const x of flat(v))
      if (isRef(x, "entry")) {
        const c = ccm.entries.find((y) => y.ccmId === x.id && y.locale === e.locale);
        for (const cv of Object.values(c?.fields ?? {})) for (const y of flat(cv)) if (isRef(y, "asset")) return assets.get(y.id)?.originalPath;
      }
  return undefined;
}

async function planSeo(rawHtml: string, ccm: CcmData) {
  const index = await readJsonOr<{ pages?: { path: string; id: string; status: number; manifest?: string }[] }>(join(rawHtml, "crawl.json"), {});
  const inputs: SeoInput[] = [];
  for (const pg of index.pages ?? []) {
    if (pg.status !== 200) continue;
    const e = ccm.entries.find((x) => x.path === pg.path);
    if (!e) continue;
    const htmlFile = [join(rawHtml, "pages", `${pg.id}.raw.html`), join(rawHtml, "pages", `${pg.id}.rendered.html`)].find((f) => existsSync(f));
    if (!htmlFile) continue;
    const canonical = e.meta?.canonical ?? e.path;
    inputs.push({
      path: pg.path,
      locale: e.locale,
      type: e.type,
      html: await readFile(htmlFile, "utf8"),
      title: e.meta?.title,
      description: e.meta?.description,
      canonicalPath: canonical,
      siteName: ccm.settings?.siteName?.[e.locale],
      imagePath: primaryImage(ccm, e),
      known: new Set([...Object.keys(e.meta?.og ?? {}), ...Object.keys(e.meta?.twitter ?? {})]),
    });
  }
  return inferSeoRules(inputs);
}

/** registry fields of a design component used by the static renderer: variant family + mined instance values */
function staticExtras(c: Design["components"][number]): string {
  const x = c as unknown as { variantOf?: string; instanceKey?: string; instanceProps?: Record<string, unknown> };
  let out = "";
  if (x.variantOf) out += `, variantOf: ${JSON.stringify(x.variantOf)}`;
  if (x.instanceProps && Object.keys(x.instanceProps).length) out += `, instanceKey: ${JSON.stringify(x.instanceKey ?? "entityId")}, instanceProps: ${JSON.stringify(x.instanceProps)}`;
  return out;
}

function emptyRegistry(): string {
  return registryHead() + "\nexport const components: Record<string, ComponentEntry> = {};\nexport const byType: Record<string, string> = {};\nexport const views: Record<string, string> = {};\nexport const templates: Record<string, TemplateDef> = {};\nexport const layout: LayoutEntry | undefined = undefined;\n";
}

