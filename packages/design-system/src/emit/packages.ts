import { TEMPLATES } from "../templates.generated.js";
import { elements, reactEventName, type ElementInfo } from "../components/registry.js";
import type { TokenSystem } from "../tokens/system.js";
import type { FileMap } from "./tokens.js";

export interface PackageNames {
  scope: string;
  version: string;
  tokens: string;
  wc: string;
  react: string;
  angular: string;
}

export function packageNames(prefix: string, version = "0.1.0"): PackageNames {
  const scope = `@${prefix}-ds`;
  return {
    scope,
    version,
    tokens: `${scope}/tokens`,
    wc: `${scope}/web-components`,
    react: `${scope}/react`,
    angular: `${scope}/angular`,
  };
}

/** Fill the prefix placeholder. */
export const fill = (s: string, prefix: string) => s.replace(/__P__/g, prefix);
const pascal = (s: string) => s.replace(/(^|[-_\s]+)(\w)/g, (_, _d, c: string) => c.toUpperCase());
const json = (v: unknown) => `${JSON.stringify(v, null, 2)}\n`;

/* ------------------------------------------------------------------ web components */

export function webComponentsPackage(t: TokenSystem, n: PackageNames): FileMap {
  const p = t.spec.prefix;
  const files: FileMap = {};
  for (const [path, src] of Object.entries(TEMPLATES))
    if (path.startsWith("web-components/")) files[path.slice("web-components/".length)] = fill(src, p);
  const els = elements();
  const byFile = new Map<string, ElementInfo[]>();
  for (const e of els) byFile.set(e.file, [...(byFile.get(e.file) ?? []), e]);
  const index = [
    `// ${t.spec.name} web components (Lit). Generated by CDR; regenerate instead of editing.`,
    ...[...byFile.entries()].map(
      ([file, es]) => `import { ${es.map((e) => e.cls).join(", ")} } from './${file}.js'`,
    ),
    "",
    `export { ${els.map((e) => e.cls).join(", ")} }`,
    "export { ICONS, icon, type IconName } from './icons.js'",
    "export { FormControl } from './form.js'",
    "export type { TableColumn, TableRow } from './components/data-table.js'",
    "",
    "/** Every element and its tag. */",
    `export const ELEMENTS = {\n${els.map((e) => `  '${p}-${e.tag}': ${e.cls},`).join("\n")}\n} as const`,
    "",
    "for (const [tag, cls] of Object.entries(ELEMENTS)) if (!customElements.get(tag)) customElements.define(tag, cls)",
    "",
    "declare global {",
    "  interface HTMLElementTagNameMap {",
    ...els.map((e) => `    '${p}-${e.tag}': ${e.cls}`),
    "  }",
    "}",
    "",
  ].join("\n");
  files["src/index.ts"] = index;
  files["package.json"] = json({
    name: n.wc,
    version: n.version,
    description: `${t.spec.name} web components built with Lit: accessible, form-associated, themed by ${n.tokens}.`,
    type: "module",
    main: "dist/index.js",
    module: "dist/index.js",
    types: "dist/index.d.ts",
    exports: { ".": { types: "./dist/index.d.ts", default: "./dist/index.js" } },
    files: ["dist", "custom-elements.json"],
    sideEffects: ["./dist/index.js"],
    customElements: "custom-elements.json",
    scripts: {
      build: "tsc -p tsconfig.build.json && node scripts/manifest.mjs",
      test: "vitest run",
    },
    dependencies: { lit: "^3.3.1", [n.tokens]: n.version },
    devDependencies: { typescript: "^5.9.3", vitest: "^3.2.4", jsdom: "^26.1.0" },
  });
  const tsconfig = {
    compilerOptions: {
      target: "ES2022",
      module: "ESNext",
      moduleResolution: "Bundler",
      lib: ["ES2022", "DOM", "DOM.Iterable"],
      strict: true,
      declaration: true,
      sourceMap: true,
      useDefineForClassFields: false,
      noImplicitOverride: true,
      skipLibCheck: true,
      outDir: "dist",
      rootDir: "src",
    },
    include: ["src"],
  };
  files["tsconfig.json"] = json({
    ...tsconfig,
    compilerOptions: { ...tsconfig.compilerOptions, noEmit: true, rootDir: "." },
    include: ["src", "test"],
  });
  files["tsconfig.build.json"] = json(tsconfig);
  files["vitest.config.ts"] =
    `import { defineConfig } from 'vitest/config'\n\nexport default defineConfig({ test: { environment: 'jsdom' } })\n`;
  files["scripts/manifest.mjs"] = manifestScript(els, p);
  files["test/elements.test.ts"] = wcTest(els, p);
  return files;
}

/** A small custom-elements.json writer (schema 2.0.0) from the docs the elements carry. */
function manifestScript(els: ElementInfo[], p: string): string {
  const modules = els.map((e) => ({
    kind: "javascript-module",
    path: `src/${e.file}.ts`,
    declarations: [
      {
        kind: "class",
        name: e.cls,
        tagName: `${p}-${e.tag}`,
        customElement: true,
        description: e.summary,
        attributes: e.props.map((a) => ({
          name: a.attribute,
          fieldName: a.name,
          type: { text: a.type },
          description: a.description,
        })),
        members: e.props.map((a) => ({
          kind: "field",
          name: a.name,
          type: { text: a.type },
          description: a.description,
        })),
        events: e.events.map((ev) => ({ name: fill(ev.name, p), description: ev.description })),
        slots: e.slots.map((s) => ({ name: s })),
      },
    ],
    exports: [
      {
        kind: "custom-element-definition",
        name: `${p}-${e.tag}`,
        declaration: { name: e.cls, module: `src/${e.file}.ts` },
      },
    ],
  }));
  return `// Writes custom-elements.json (read by IDEs, Storybook and the docs). Generated by CDR.
import { writeFileSync } from 'node:fs'

const manifest = ${JSON.stringify({ schemaVersion: "2.0.0", modules }, null, 2)}

writeFileSync(new URL('../custom-elements.json', import.meta.url), JSON.stringify(manifest, null, 2) + '\\n')
`;
}

function wcTest(els: ElementInfo[], p: string): string {
  return `import { describe, expect, it } from 'vitest'
import '../src/index.js'

const tags = ${JSON.stringify(els.map((e) => `${p}-${e.tag}`))}

const mount = async <T extends HTMLElement>(html: string): Promise<T> => {
  document.body.innerHTML = html
  const el = document.body.firstElementChild as T & { updateComplete?: Promise<unknown> }
  await el.updateComplete
  return el
}

describe('${p} web components', () => {
  it('defines every element', () => {
    for (const tag of tags) expect(customElements.get(tag), tag).toBeTruthy()
  })

  it('renders a button with the label slot', async () => {
    const el = await mount('<${p}-button kind="secondary">Save</${p}-button>')
    expect(el.shadowRoot!.querySelector('button')).toBeTruthy()
    expect(el.getAttribute('kind')).toBe('secondary')
  })

  it('toggles a checkbox and fires change', async () => {
    const el = await mount<HTMLElement & { checked: boolean; toggle(): void; updateComplete: Promise<unknown> }>('<${p}-checkbox label="Yes"></${p}-checkbox>')
    let changes = 0
    el.addEventListener('change', () => changes++)
    el.toggle()
    await el.updateComplete
    expect(el.checked).toBe(true)
    expect(changes).toBe(1)
  })

  it('toggle has the switch role', async () => {
    const el = await mount('<${p}-toggle label="Wi-Fi"></${p}-toggle>')
    expect(el.shadowRoot!.querySelector('[role="switch"]')?.getAttribute('aria-checked')).toBe('false')
  })

  it('tag dismiss is cancelable and hides the tag', async () => {
    const el = await mount('<${p}-tag filter>Filter</${p}-tag>')
    let fired = 0
    el.addEventListener('${p}-dismiss', () => fired++)
    ;(el.shadowRoot!.querySelector('button') as HTMLButtonElement).click()
    expect(fired).toBe(1)
    expect(el.hidden).toBe(true)
  })

  it('sorts a data table', async () => {
    const el = await mount<HTMLElement & { columns: unknown; rows: unknown; updateComplete: Promise<unknown> }>('<${p}-data-table></${p}-data-table>')
    el.columns = [{ key: 'name', header: 'Name', sortable: true }]
    el.rows = [{ name: 'b' }, { name: 'a' }]
    await el.updateComplete
    ;(el.shadowRoot!.querySelector('th button') as HTMLButtonElement).click()
    await el.updateComplete
    const cells = [...el.shadowRoot!.querySelectorAll('td')].map((td) => td.textContent?.trim())
    expect(cells).toEqual(['a', 'b'])
    expect(el.shadowRoot!.querySelector('th')?.getAttribute('aria-sort')).toBe('ascending')
  })
})
`;
}

/* ------------------------------------------------------------------ React */

export function reactPackage(t: TokenSystem, n: PackageNames): FileMap {
  const p = t.spec.prefix;
  const els = elements();
  const lines = [
    `// ${t.spec.name} React components: typed wrappers over ${n.wc} (@lit/react). Generated by CDR.`,
    "import * as React from 'react'",
    "import { createComponent } from '@lit/react'",
    `import {\n${els.map((e) => `  ${e.cls} as ${e.cls}Element,`).join("\n")}\n} from '${n.wc}'`,
    "",
    `export type { TableColumn, TableRow, IconName } from '${n.wc}'`,
    "",
  ];
  for (const e of els) {
    const events = e.events.map((ev) => `    ${reactEventName(ev.name)}: '${fill(ev.name, p)}',`);
    lines.push(
      `/** ${e.summary.replace(/\*\//g, "")} */`,
      `export const ${e.cls} = createComponent({`,
      `  tagName: '${p}-${e.tag}',`,
      `  elementClass: ${e.cls}Element,`,
      "  react: React,",
      events.length ? `  events: {\n${events.join("\n")}\n  },` : "  events: {},",
      "})",
      "",
    );
  }
  lines.push(
    `export type ThemeName = 'light' | 'light-alt' | 'dark' | 'darkest'`,
    "",
    "/** Sets a theme for everything inside it. */",
    "export function Theme({ theme, as = 'div', children, ...rest }: { theme: ThemeName; as?: keyof React.JSX.IntrinsicElements; children?: React.ReactNode } & React.HTMLAttributes<HTMLElement>) {",
    `  return React.createElement(as, { ...rest, 'data-${p}-theme': theme }, children)`,
    "}",
    "",
  );
  return {
    "package.json": json({
      name: n.react,
      version: n.version,
      description: `${t.spec.name} React components (typed wrappers over ${n.wc}).`,
      type: "module",
      main: "dist/index.js",
      types: "dist/index.d.ts",
      exports: { ".": { types: "./dist/index.d.ts", default: "./dist/index.js" } },
      files: ["dist"],
      sideEffects: false,
      scripts: { build: "tsc -p tsconfig.json", test: "node --test test/*.test.mjs" },
      dependencies: { "@lit/react": "^1.0.8", [n.wc]: n.version },
      peerDependencies: { react: ">=18" },
      devDependencies: { typescript: "^5.9.3", "@types/react": "^18.3.31", react: "^18.3.1" },
    }),
    "tsconfig.json": json({
      compilerOptions: {
        target: "ES2022",
        module: "ESNext",
        moduleResolution: "Bundler",
        lib: ["ES2022", "DOM", "DOM.Iterable"],
        jsx: "react-jsx",
        strict: true,
        declaration: true,
        skipLibCheck: true,
        outDir: "dist",
        rootDir: "src",
      },
      include: ["src"],
    }),
    "src/index.ts": lines.join("\n"),
    "test/exports.test.mjs": `import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

test('every element has a React wrapper', () => {
  const src = readFileSync(new URL('../src/index.ts', import.meta.url), 'utf8')
  for (const name of ${JSON.stringify(els.map((e) => e.cls))}) assert.match(src, new RegExp('export const ' + name + ' = createComponent'))
})
`,
  };
}

/* ------------------------------------------------------------------ Angular */

export function angularPackage(t: TokenSystem, n: PackageNames): FileMap {
  const p = t.spec.prefix;
  const P = pascal(p);
  const els = elements();
  const files: FileMap = {};
  const exportsList: string[] = [];
  for (const e of els) {
    const dir = `${P}${e.cls}Directive`;
    exportsList.push(dir);
    const inputs = e.props.map(
      (a) =>
        `  /** ${a.description || a.name} */\n  @Input() set ${a.name}(v: ${e.cls}Element['${a.name}']) {\n    this.el.${a.name} = v\n  }\n  get ${a.name}(): ${e.cls}Element['${a.name}'] {\n    return this.el.${a.name}\n  }`,
    );
    const custom = e.events.filter((ev) => ev.name.startsWith("__P__-"));
    const outputs = custom.map((ev) => {
      const out = `${p}${pascal(ev.name.replace("__P__-", ""))}`;
      return `  /** ${ev.description} */\n  @Output() readonly ${out} = new EventEmitter<CustomEvent>()\n  @HostListener('${fill(ev.name, p)}', ['$event'])\n  protected _${out}(e: CustomEvent) {\n    this.${out}.emit(e)\n  }`;
    });
    files[`src/lib/${e.tag}.directive.ts`] = [
      `import { Directive, ElementRef, EventEmitter, HostListener, Input, Output, inject } from '@angular/core'`,
      `import type { ${e.cls} as ${e.cls}Element } from '${n.wc}'`,
      "",
      `/** ${e.summary.replace(/\*\//g, "")} */`,
      `@Directive({ selector: '${p}-${e.tag}', standalone: true })`,
      `export class ${dir} {`,
      `  protected readonly el = inject<ElementRef<${e.cls}Element>>(ElementRef).nativeElement`,
      ...(inputs.length ? ["", inputs.join("\n\n")] : []),
      ...(outputs.length ? ["", outputs.join("\n\n")] : []),
      `}`,
      "",
    ]
      .join("\n")
      .replace(
        /import \{ Directive, ElementRef, EventEmitter, HostListener, Input, Output, inject \}/,
        () => {
          const used = ["Directive", "ElementRef", "inject"];
          if (inputs.length) used.push("Input");
          if (outputs.length) used.push("EventEmitter", "HostListener", "Output");
          return `import { ${used.sort().join(", ")} }`;
        },
      );
    if (e.form) {
      const cva = `${P}${e.cls}ValueAccessor`;
      exportsList.push(cva);
      const prop = e.form === "checked" ? "checked" : "value";
      const read = e.form === "checked" ? "($any($event.target)).checked" : "($any($event.target)).value";
      const live =
        e.form === "checked" || e.tag === "select" || e.tag === "dropdown" || e.tag === "radio-group"
          ? "change"
          : "input";
      files[`src/lib/${e.tag}.value-accessor.ts`] =
        `import { Directive, ElementRef, forwardRef, inject } from '@angular/core'
import { NG_VALUE_ACCESSOR, type ControlValueAccessor } from '@angular/forms'
import type { ${e.cls} as ${e.cls}Element } from '${n.wc}'

/** Lets \`${p}-${e.tag}\` work with ngModel, formControl and formControlName. */
@Directive({
  selector: '${p}-${e.tag}[ngModel], ${p}-${e.tag}[formControl], ${p}-${e.tag}[formControlName]',
  standalone: true,
  providers: [{ provide: NG_VALUE_ACCESSOR, useExisting: forwardRef(() => ${cva}), multi: true }],
  host: { '(${live})': 'onChange(${read})', '(focusout)': 'onTouched()' },
})
export class ${cva} implements ControlValueAccessor {
  private readonly el = inject<ElementRef<${e.cls}Element>>(ElementRef).nativeElement
  onChange: (value: unknown) => void = () => {}
  onTouched: () => void = () => {}
  writeValue(value: unknown): void {
    this.el.${prop} = ${e.form === "checked" ? "!!value" : "value == null ? '' : String(value)"}
  }
  registerOnChange(fn: (value: unknown) => void): void {
    this.onChange = fn
  }
  registerOnTouched(fn: () => void): void {
    this.onTouched = fn
  }
  setDisabledState(disabled: boolean): void {
    this.el.disabled = disabled
  }
}
`
          .replace("$any($event.target)", "$event.target")
          .replace("$any($event.target)", "$event.target");
    }
  }
  const imports = els.flatMap((e) => [
    `import { ${P}${e.cls}Directive } from './lib/${e.tag}.directive'`,
    ...(e.form ? [`import { ${P}${e.cls}ValueAccessor } from './lib/${e.tag}.value-accessor'`] : []),
  ]);
  files["src/public-api.ts"] = [
    `// ${t.spec.name} for Angular: standalone directives over ${n.wc}, with ControlValueAccessors. Generated by CDR.`,
    `import { NgModule } from '@angular/core'`,
    `import '${n.wc}'`,
    ...imports,
    "",
    `export { ${exportsList.join(", ")} }`,
    "",
    "/** Every directive and value accessor, for a standalone component's `imports`. */",
    `export const ${P.toUpperCase()}_COMPONENTS = [${exportsList.join(", ")}] as const`,
    "",
    "/**",
    ` * NgModule with every directive. Components that use the elements also need`,
    " * `schemas: [CUSTOM_ELEMENTS_SCHEMA]`, because Angular only knows its own components' tags.",
    " */",
    `@NgModule({ imports: [...${P.toUpperCase()}_COMPONENTS], exports: [...${P.toUpperCase()}_COMPONENTS] })`,
    `export class ${P}ComponentsModule {}`,
    "",
  ].join("\n");
  files["package.json"] = json({
    name: n.angular,
    version: n.version,
    description: `${t.spec.name} for Angular: standalone directives and form value accessors over ${n.wc}.`,
    scripts: { build: "ng-packagr -p ng-package.json", test: "node --test test/*.test.mjs" },
    peerDependencies: { "@angular/core": ">=17", "@angular/forms": ">=17" },
    dependencies: { [n.wc]: n.version, tslib: "^2.8.1" },
    devDependencies: {
      "@angular/compiler": "^19.2.0",
      "@angular/compiler-cli": "^19.2.0",
      "@angular/core": "^19.2.0",
      "@angular/forms": "^19.2.0",
      "ng-packagr": "^19.2.0",
      rxjs: "^7.8.2",
      typescript: "~5.7.3",
    },
  });
  files["ng-package.json"] = json({
    $schema: "./node_modules/ng-packagr/ng-package.schema.json",
    dest: "dist",
    lib: { entryFile: "src/public-api.ts" },
    allowedNonPeerDependencies: [n.wc, "tslib"],
  });
  files["tsconfig.json"] = json({
    compilerOptions: {
      target: "ES2022",
      module: "ES2022",
      moduleResolution: "bundler",
      lib: ["ES2022", "DOM"],
      strict: true,
      declaration: true,
      experimentalDecorators: true,
      useDefineForClassFields: false,
      skipLibCheck: true,
    },
    angularCompilerOptions: { compilationMode: "partial", strictTemplates: true },
    include: ["src"],
  });
  files["tsconfig.lib.json"] = json({ extends: "./tsconfig.json", compilerOptions: { outDir: "dist" } });
  files["test/api.test.mjs"] = `import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

test('every element has a directive, form elements a value accessor', () => {
  const api = readFileSync(new URL('../src/public-api.ts', import.meta.url), 'utf8')
  for (const name of ${JSON.stringify(exportsList)}) assert.match(api, new RegExp('\\\\b' + name + '\\\\b'))
})
`;
  return files;
}
