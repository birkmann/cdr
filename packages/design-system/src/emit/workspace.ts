import { elements } from "../components/registry.js";
import type { BrandSpec } from "../spec.js";
import { buildTokenSystem, THEMES, THEME_LABELS, type TokenSystem } from "../tokens/system.js";
import { docsApp } from "./docs.js";
import {
  angularPackage,
  packageNames,
  reactPackage,
  webComponentsPackage,
  type PackageNames,
} from "./packages.js";
import { tokensPackage, type FileMap } from "./tokens.js";

export interface Workspace {
  files: FileMap;
  tokens: TokenSystem;
  names: PackageNames;
}

const prefixed = (prefix: string, files: FileMap) =>
  Object.fromEntries(Object.entries(files).map(([k, v]) => [`${prefix}/${k}`, v]));

/** The whole design-system workspace for a brand spec (pure; nothing is written). */
export function buildWorkspace(spec: BrandSpec, o: { version?: string } = {}): Workspace {
  const t = buildTokenSystem(spec);
  const n = packageNames(spec.prefix, o.version);
  const files: FileMap = {
    ...prefixed("packages/tokens", tokensPackage(t, n.scope, n.version)),
    ...prefixed("packages/web-components", webComponentsPackage(t, n)),
    ...prefixed("packages/react", reactPackage(t, n)),
    ...prefixed("packages/angular", angularPackage(t, n)),
    ...prefixed("docs", docsApp(t, n)),
    "package.json": `${JSON.stringify(
      {
        name: `${n.scope}/workspace`,
        private: true,
        version: n.version,
        description: `${spec.name} design system: tokens, Lit web components, React and Angular. Generated by CDR.`,
        workspaces: [
          "packages/tokens",
          "packages/web-components",
          "packages/react",
          "packages/angular",
          "docs",
        ],
        scripts: {
          build: "npm run build -w packages/tokens -w packages/web-components -w packages/react",
          "build:angular": "npm run build -w packages/angular",
          test: "npm test -w packages/tokens -w packages/web-components -w packages/react -w packages/angular",
          docs: "npm run dev -w docs",
          "docs:build": "npm run build -w docs",
        },
      },
      null,
      2,
    )}\n`,
    ".gitignore": "node_modules/\ndist/\n*.tsbuildinfo\n",
    "brand.json": `${JSON.stringify(spec, null, 2)}\n`,
    "README.md": readme(t, n),
    "DESIGN.md": design(t),
  };
  return { files, tokens: t, names: n };
}

function readme(t: TokenSystem, n: PackageNames): string {
  const p = t.spec.prefix;
  const els = elements().filter((e) => !e.child);
  return `# ${t.spec.name} design system

Tokens with four themes, ${els.length} accessible components as Lit web components, typed React components and Angular directives, and a docs site. Generated by CDR from \`brand.json\`.

| Package | What it is |
| --- | --- |
| \`${n.tokens}\` | Design tokens: CSS variables (\`--${p}-…\`) with themes ${THEMES.map((x) => `\`${x}\``).join(", ")}, a grid, SCSS, JS/TS, DTCG JSON, a Tailwind preset |
| \`${n.wc}\` | The components as custom elements (\`<${p}-button>\` …), built with Lit: keyboard support, ARIA, form association |
| \`${n.react}\` | React components over the web components, with typed props and \`onX\` events |
| \`${n.angular}\` | Standalone Angular directives with typed inputs and outputs, plus \`ControlValueAccessor\`s for forms |
| \`docs\` | The docs site: foundations, every component in every theme, code for each framework |

## Develop

\`\`\`bash
npm install
npm run build        # tokens, web components, React
npm test
npm run docs         # docs at http://localhost:5173
npm run build:angular   # the Angular library (ng-packagr)
\`\`\`

\`docs/foundations.html\` opens without any build: colours, themes, contrast, type and spacing.

## Use

Load the tokens once, then use the components.

\`\`\`html
<link rel="stylesheet" href="node_modules/${n.tokens}/css/tokens.css">
<script type="module">import '${n.wc}'</script>

<${p}-button kind="primary">Save</${p}-button>
\`\`\`

**React**

\`\`\`tsx
import '${n.tokens}/tokens.css'
import { Button, TextInput, Theme } from '${n.react}'

<Theme theme="dark">
  <TextInput label="Email" onInput={(e) => setEmail(e.currentTarget.value)} />
  <Button kind="primary" onClick={save}>Save</Button>
</Theme>
\`\`\`

**Angular**

\`\`\`ts
import { CUSTOM_ELEMENTS_SCHEMA, Component } from '@angular/core'
import { FormsModule } from '@angular/forms'
import { ${p.toUpperCase()}_COMPONENTS } from '${n.angular}'

@Component({
  imports: [FormsModule, ...${p.toUpperCase()}_COMPONENTS],
  schemas: [CUSTOM_ELEMENTS_SCHEMA],
  template: \`<${p}-text-input label="Email" [(ngModel)]="email"></${p}-text-input>\`,
})
export class SignUp { email = '' }
\`\`\`

Add \`${n.tokens}/css/tokens.css\` to the \`styles\` of \`angular.json\`.

## Themes

\`:root\` carries the default theme (${THEME_LABELS[t.defaultTheme]}). Set another one on any element: \`data-${p}-theme="dark"\` or the class \`${p}-theme--dark\`. The themes are ${THEMES.map((x) => `\`${x}\``).join(", ")}.

## Server-side rendering

The React components render the custom elements. Their shadow DOM appears once the web components load in the browser, so render them on the client or accept that they upgrade after hydration.

## Regenerate

Edit \`brand.json\` (colours, fonts, radii, density, control height) and ask CDR to regenerate the design system with the same folder. Generated files are overwritten, so put your own code next to them, not inside them.
`;
}

function design(t: TokenSystem): string {
  const s = t.spec;
  const src = (k: string) => (s.sources?.[k] ? ` _(${s.sources[k]})_` : "");
  const failing = t.contrast.filter((c) => !c.pass);
  return `# ${s.name}: design notes

## The brand reading

| | Value | |
| --- | --- | --- |
| Primary | \`${s.colors.primary}\` | base step ${t.baseSteps.primary}${src("colors.primary")} |
${(["secondary", "accent", "success", "warning", "danger", "info", "background", "surface", "text"] as const)
  .filter((k) => s.colors[k])
  .map((k) => `| ${k[0]!.toUpperCase()}${k.slice(1)} | \`${s.colors[k]}\` | ${src(`colors.${k}`)} |`)
  .join("\n")}
| Theme | ${s.theme} → default theme \`${t.defaultTheme}\` | ${src("theme")} |
| Fonts | ${s.fonts.sans}${s.fonts.display ? ` · display ${s.fonts.display}` : ""} · mono ${t.fonts.mono} | ${src("fonts.sans")} |
| Radius | control ${s.radius.control}px, container ${s.radius.container}px | ${src("radius.control")} |
| Controls | ${t.sizes.sm} / ${t.sizes.md} / ${t.sizes.lg} px, ${s.density} density | ${src("controlHeight")} |
| Buttons | secondary ${s.buttons.secondary}${s.buttons.uppercase ? ", uppercase labels" : ""} | ${src("buttons.secondary")} |
| Elevation | ${s.elevation} | ${src("elevation")} |

${s.notes?.length ? `${s.notes.map((x) => `- ${x}`).join("\n")}\n` : ""}
## Token tiers

1. **Palettes**: ten steps per hue (\`--${s.prefix}-primary-60\`). The brand colour keeps its exact value at its base step.
2. **Semantic tokens**: what a colour is for (\`--${s.prefix}-interactive\`, \`--${s.prefix}-text-secondary\`, \`--${s.prefix}-layer-01\`), with one value per theme.
3. **Components** use semantic tokens only. A new theme or brand changes no component code.

## Accessibility

- Contrast: ${failing.length ? `${failing.length} pair(s) below minimum, see \`packages/tokens/contrast.json\`.` : `all ${t.contrast.length} checked pairs pass in every theme (text 4.5:1, focus, borders and icons 3:1).`} Colours that would fail are moved along their palette, so the brand colour is kept wherever it reads.
- Every interactive element follows its WAI-ARIA Authoring Practices pattern: roles, states, keyboard support (tabs, radio groups and the dropdown use arrow keys; modals trap focus and close with Esc).
- Focus is always visible: a 2 px \`--${s.prefix}-focus\` outline on \`:focus-visible\`.
- Motion honours \`prefers-reduced-motion\`: every duration token becomes 0.
`;
}
